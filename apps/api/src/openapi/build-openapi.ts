import { apiErrorSchema } from '@devmsr/validation';
import { z, type ZodType } from 'zod';
import type { RouteInfo } from '../common/routes/route-catalog.js';

type JsonSchema = Record<string, unknown>;

interface Parameter {
  name: string;
  in: 'path' | 'query' | 'header';
  required: boolean;
  description?: string;
  schema: JsonSchema;
}

export interface OpenApiDocument {
  openapi: string;
  info: { title: string; version: string; description: string };
  paths: Record<string, Record<string, unknown>>;
  components: { schemas: Record<string, JsonSchema>; securitySchemes: Record<string, unknown> };
}

const ERROR_REF = { $ref: '#/components/schemas/ApiError' };

function toJsonSchema(schema: ZodType, io: 'input' | 'output'): JsonSchema {
  // The document declares the dialect once, so each schema drops its own $schema.
  const { $schema, ...rest } = z.toJSONSchema(schema, { target: 'draft-2020-12', io, unrepresentable: 'any' });
  return rest;
}

/** `AuthController.login` becomes `authLogin`. */
function operationId(route: RouteInfo): string {
  const [controller = '', handler = ''] = route.id.split('.');
  const base = controller.replace(/Controller$/, '');
  return `${base.charAt(0).toLowerCase()}${base.slice(1)}${handler.charAt(0).toUpperCase()}${handler.slice(1)}`;
}

function pascal(value: string): string {
  return `${value.charAt(0).toUpperCase()}${value.slice(1)}`;
}

/** One parameter per property of an object schema (route params or query). */
function parametersFrom(schema: ZodType | undefined, location: 'path' | 'query'): Parameter[] {
  if (schema === undefined) return [];
  const json = toJsonSchema(schema, 'input');
  const properties = (json['properties'] ?? {}) as Record<string, JsonSchema>;
  const required = new Set((json['required'] ?? []) as string[]);
  return Object.entries(properties).map(([name, property]) => ({
    name,
    in: location,
    required: location === 'path' || required.has(name),
    schema: property,
  }));
}

/** OpenAPI 3.1 for every route, built from the route catalog and each route's Zod contract. */
export function buildOpenApi(routes: RouteInfo[]): OpenApiDocument {
  const schemas: Record<string, JsonSchema> = { ApiError: toJsonSchema(apiErrorSchema, 'output') };
  const paths: OpenApiDocument['paths'] = {};

  for (const route of routes) {
    const contract = route.contract;
    if (contract === undefined) continue;
    const id = operationId(route);
    const path = route.path.replace(/:([A-Za-z]+)/g, '{$1}');
    const unsafe = route.method !== 'GET';

    const parameters: Parameter[] = [...parametersFrom(contract.params, 'path'), ...parametersFrom(contract.query, 'query')];
    if (unsafe) {
      parameters.push({ name: 'X-CSRF-Token', in: 'header', required: true, description: 'Value of the CSRF cookie', schema: { type: 'string' } });
    }
    if (route.idempotent) {
      parameters.push({
        name: 'Idempotency-Key',
        in: 'header',
        required: true,
        description: 'Unique per financial request. A repeat returns the stored response.',
        schema: { type: 'string', pattern: '^[A-Za-z0-9_-]{16,128}$' },
      });
    }

    let requestBody: unknown;
    if (contract.body !== undefined) {
      schemas[`${pascal(id)}Request`] = toJsonSchema(contract.body, 'input');
      requestBody = { required: true, content: { 'application/json': { schema: { $ref: `#/components/schemas/${pascal(id)}Request` } } } };
    }

    let success: unknown = { description: 'No content' };
    if (contract.response !== undefined) {
      schemas[`${pascal(id)}Response`] = toJsonSchema(contract.response, 'output');
      success = { description: 'Success', content: { [contract.contentType ?? 'application/json']: { schema: { $ref: `#/components/schemas/${pascal(id)}Response` } } } };
    }

    paths[path] ??= {};
    paths[path][route.method.toLowerCase()] = {
      operationId: id,
      summary: contract.summary,
      tags: [path.split('/')[3] ?? 'api'],
      'x-permission': route.isPublic ? 'public' : route.permission,
      security: route.isPublic ? [] : [{ session: [] }],
      ...(parameters.length > 0 ? { parameters } : {}),
      ...(requestBody === undefined ? {} : { requestBody }),
      responses: {
        [String(route.status)]: success,
        default: { description: 'Error', content: { 'application/json': { schema: ERROR_REF } } },
      },
    };
  }

  return {
    openapi: '3.1.0',
    info: {
      title: 'DevMSR HMS API',
      version: '1',
      description: 'Generated by `pnpm api:spec` from the route contracts. Do not edit by hand.',
    },
    paths,
    components: {
      schemas,
      securitySchemes: {
        session: {
          type: 'apiKey',
          in: 'cookie',
          name: 'hms_session',
          description: 'Session cookie set by POST /auth/login. Named __Secure-hms_session in production.',
        },
      },
    },
  };
}
